/**
 * Is this source file really a generated binary blob wearing a source
 * extension?
 *
 * LVGL image converters, `xxd -i`, font converters and the SDK's own lcdc
 * tooling all emit `.c`/`.h` files whose entire body is one giant initializer:
 *
 *     const uint8_t image_bg_map[] = {
 *         0x00, 0x00, 0x00, ...        // ~500 000 of these
 *     };
 *
 * They are not code. Chunking them produces hex dumps the chunker cannot
 * name (`declaration` rows averaging 2.3 KB), and every one of those chunks
 * costs an embedding. Measured on the loong SDK: 344 such files hold 483 MiB
 * — 46% of the tree's source bytes — while the remaining 4 828 C/H files carry
 * the actual code.
 *
 * The heuristic is GitHub Linguist's, adapted for C-family data blobs.
 * Linguist classifies minified JS/CSS as generated when the average line
 * length exceeds 110 characters; the same signal works here, raised to 160
 * because C headers legitimately wrap long declarations. Verified against the
 * loong SDK: 342 files caught, and of those only 6 are not obviously data
 * (all are audio coefficient tables — still data).
 *
 * Deliberately NOT a size threshold. `MAX_FILE_SIZE` already refuses the
 * extreme cases (26 MiB image_bg.c); the 490 MiB this catches is mostly
 * 100 KB–2 MB files that a size rule would miss.
 */

/** Average non-blank line length above which a C-family file is generated data. */
export const GENERATED_AVG_LINE_CHARS = 160;

/**
 * Upper bound on how much of the file we read. The signal is a property of
 * the bulk of the file, and a 26 MiB read per candidate would cost more than
 * chunking it. A blob's first 256 KiB is statistically identical to the rest.
 */
const SAMPLE_BYTES = 256 * 1024;

/**
 * More real definitions than this and the file is code with some tables in
 * it — `arm_common_tables.c` has a handful of accessor functions and is worth
 * indexing for them even though its body is twiddle factors. Guarding on
 * definition count keeps the rule from swallowing mixed files.
 */
const MAX_DEFINITIONS_WHEN_GENERATED = 2;

const DEFINITION_LINE = /^\s*(?:static\s+|inline\s+|extern\s+)*[A-Za-z_][\w \t*]*\s+\**[A-Za-z_]\w*\s*\([^;]*\)\s*\{?\s*$/;

/**
 * Numeric literal density, measured over the RAW sample rather than over line
 * shapes.
 *
 * Line-based checks miss three of the four shapes this has to catch:
 *
 *   jpeg_data.c       12 hex bytes per line   avg 72 chars  → under any line threshold
 *   audio 48k_2c.h    the whole array on ONE line            → avg 262 144, no "lines"
 *   bsp_rgb_shift.h   40 hex bytes per line   avg 231 chars  → caught by line length
 *   img_star.c        40 decimal per line     avg 437 chars  → caught by line length
 *
 * A byte-array initializer is the same file whichever way the generator wrapped
 * it, so the stable signal is how much of the text is `0xNN`/`NNN` separated by
 * commas. Real C is mostly identifiers, operators and whitespace; a data blob
 * is almost nothing else.
 */
const DATA_LITERAL = /(?:0x[0-9a-fA-F]{1,2}|\d{1,5})\s*,\s*/g;

/** Share of `sample` that must be numeric-literal-plus-comma to call it data. */
const DATA_LITERAL_RATIO = 0.6;

/** Code languages whose "source" can be a generated byte array. */
const C_FAMILY = new Set(['.c', '.h', '.cc', '.cpp', '.cxx', '.hpp', '.hxx', '.hh', '.inc']);

export interface GeneratedDataVerdict {
  generated: boolean;
  /** Average non-blank line length of the sampled text; 0 when not computed. */
  avgLineChars: number;
  /** Definition-shaped lines found in the sample. */
  definitions: number;
  /** Share of the sample consumed by `0xNN,`/`NNN,` literals. */
  dataLiteralRatio: number;
}

/**
 * Classify a candidate file. `language` is the detected code language (as the
 * chunker reports it); only C-family languages are considered, so a dense
 * minified `.js` — which Linguist also catches — is left to the existing
 * extension-based rules rather than silently dropped here.
 */
export function classifyGeneratedDataFile(sample: string, language: string): GeneratedDataVerdict {
  const ext = language.startsWith('.') ? language.toLowerCase() : `.${language.toLowerCase()}`;
  if (!C_FAMILY.has(ext)) return { generated: false, avgLineChars: 0, definitions: 0, dataLiteralRatio: 0 };

  const lines = sample.split('\n').filter((line) => line.trim().length > 0);
  if (lines.length === 0) return { generated: false, avgLineChars: 0, definitions: 0, dataLiteralRatio: 0 };

  const avgLineChars = lines.reduce((sum, line) => sum + line.length, 0) / lines.length;
  let definitions = 0;
  for (const line of lines) if (DEFINITION_LINE.test(line)) definitions += 1;

  // Both signals, either one sufficient:
  //  - literal ratio: wrap-independent, catches one-line and 12-per-line blobs;
  //  - average line length: catches blobs whose numbers dominate less (mixed
  //    decimal/hex, or a trailing manifest section) but which are plainly
  //    machine-packed.
  const literals = sample.match(DATA_LITERAL) ?? [];
  const literalChars = literals.reduce((sum, match) => sum + match.length, 0);
  const dataLiteralRatio = sample.length > 0 ? literalChars / sample.length : 0;

  const looksLikeData = dataLiteralRatio >= DATA_LITERAL_RATIO
    || (avgLineChars > GENERATED_AVG_LINE_CHARS && dataLiteralRatio >= 0.3);

  const generated = definitions <= MAX_DEFINITIONS_WHEN_GENERATED && looksLikeData;
  return { generated, avgLineChars, definitions, dataLiteralRatio };
}

/**
 * Read at most `SAMPLE_BYTES` from `filePath` and classify it. Never throws:
 * an unreadable file is not generated (it will surface its own error later),
 * which keeps this filter from changing error accounting.
 */
export function isGeneratedDataFileSync(filePath: string, language: string, readSync: (path: string, limit: number) => string): GeneratedDataVerdict {
  let sample: string;
  try {
    sample = readSync(filePath, SAMPLE_BYTES);
  } catch {
    return { generated: false, avgLineChars: 0, definitions: 0, dataLiteralRatio: 0 };
  }
  return classifyGeneratedDataFile(sample, language);
}

export { SAMPLE_BYTES };
